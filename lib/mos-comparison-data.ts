export async function fetchLiveMosComparisonRows(sheetId = "11Wfxz7mFVR2Gq1vuSsix_pQSVhQXgDl3Tk1B4eaKSFs"): Promise<{
  rows: MosComparisonRow[];
  revisionDate: string;
} | null> {
  try {
    const url = `https://docs.google.com/spreadsheets/d/${sheetId}/gviz/tq?tqx=out:json&sheet=MOS%20Comparison`;
    const res = await fetch(url, { cache: "no-store" });
    if (!res.ok) return null;
    const text = await res.text();
    const start = text.indexOf("{");
    const end = text.lastIndexOf("}");
    if (start === -1 || end === -1) return null;
    const data = JSON.parse(text.substring(start, end + 1));
    const tableRows = data?.table?.rows;
    if (!Array.isArray(tableRows)) return null;

    let revisionDate = MOS_COMPARISON_META.revisionDate;
    const colGLabel = String(data?.table?.cols?.[6]?.label || "");
    const revMatch = colGLabel.match(/Revision\s*Date\s*:\s*(.+)$/i);
    if (revMatch?.[1]) {
      revisionDate = revMatch[1].trim();
    }

    const parsed: MosComparisonRow[] = [];
    for (const r of tableRows) {
      const cells = Array.isArray(r?.c) ? r.c : [];
      const vals = cells.map((c: { f?: unknown; v?: unknown } | null) =>
        c ? String(c.f ?? c.v ?? "").trim() : ""
      );
      const no = Number(vals[0]);
      if (!Number.isFinite(no) || no <= 0 || vals[0].toUpperCase() === "NO") continue;
      if (!vals[1] && !vals[2] && !vals[3] && !vals[5]) continue;
      parsed.push({
        no,
        trade: vals[1] || "",
        workItem: vals[2] || "",
        accRefA: vals[3] || "",
        descriptionA: vals[4] || "",
        accRefB: vals[5] || "",
        descriptionB: vals[6] || "",
      });
    }

    if (parsed.length === 0) return null;
    return { rows: parsed, revisionDate };
  } catch (err) {
    console.error("Failed to fetch live MOS Comparison sheet:", err);
    return null;
  }
}
